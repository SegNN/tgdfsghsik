#!/usr/bin/env python3
"""Carry the 1.16.5 server tuning over to the 1.21.4 configs.

Works line-by-line on the NEW config so every comment, blank line and key order that
1.21.4 generated is preserved byte-for-byte; only the scalar VALUES that the operator
had customised on 1.16.5 are rewritten.

A key is only touched when the exact same dotted path still exists in the new file.
Everything that could not be mapped is reported so it can be handled by hand.
"""
import os, re, sys, yaml

OLD = "/home/fluge/Загрузки/AyuGram Desktop/FichaWorld v6.0 Free"
NEW = "/home/fluge/Загрузки/AyuGram Desktop/FichaWorld v6.1 (1.21.4)"
# pristine configs generated by the ORIGINAL Purpur 1.16.5 jar, used to tell a real
# operator customisation apart from a value that merely changed default between versions
DEF = "/tmp/claude-1000/-home-fluge----------AyuGram-Desktop-FichaWorld-v6-0-Free/7c439c29-abf7-4be1-a5b2-4abb60c39156/scratchpad/defaults-1165"

# old file -> new file(s) it may feed
PAIRS = [
    ("bukkit.yml",  ["bukkit.yml"]),
    ("spigot.yml",  ["spigot.yml"]),
    ("purpur.yml",  ["purpur.yml"]),
    ("paper.yml",   ["config/paper-global.yml", "config/paper-world-defaults.yml"]),
]

# never carry these over - they are version/bookkeeping fields or would break 1.21.4
SKIP_PATHS = {
    "config-version", "settings.config-version", "verbose",
    "settings.minimum-api",           # 1.16-era value
    "settings.shutdown-message",      # handled separately (kept, but see below)
    "aliases",
}
SKIP_PREFIXES = ("settings.unsupported-settings.",)   # readme strings etc.


def flatten(node, prefix=""):
    out = {}
    if isinstance(node, dict):
        for k, v in node.items():
            out.update(flatten(v, f"{prefix}{k}." if prefix else f"{k}."))
    else:
        out[prefix[:-1]] = node
    return out


def fmt(value, original_line):
    """Render `value` the way this file already renders scalars."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if value is None:
        return ""
    if isinstance(value, (int, float)):
        return str(value)
    s = str(value)
    # keep the original quoting style if the new line was quoted
    m = re.search(r":\s*(['\"])", original_line)
    if m or re.search(r"[:#&*{}\[\],>|%@`]|^\s|\s$|^$", s):
        q = m.group(1) if m else "'"
        return q + s.replace(q, q * 2 if q == "'" else "\\" + q) + q
    return s


def migrate(old_path, new_path, def_path):
    if not (os.path.isfile(old_path) and os.path.isfile(new_path)):
        return None
    try:
        old_doc = yaml.safe_load(open(old_path, encoding="utf-8")) or {}
    except Exception as e:
        return ("PARSE FAIL", str(e), [], [])
    old_flat = flatten(old_doc)

    # keep ONLY the paths the operator actually changed away from the 1.16.5 default.
    # without this, 1.16.5 defaults would clobber deliberate 1.21.4 defaults - e.g.
    # purpur ridable-max-y 256 -> 320 is the 1.18 world-height change, not a setting.
    if def_path and os.path.isfile(def_path):
        try:
            def_flat = flatten(yaml.safe_load(open(def_path, encoding="utf-8")) or {})
            old_flat = {p: v for p, v in old_flat.items()
                        if p not in def_flat or def_flat[p] != v}
        except Exception as e:
            print(f"  !! could not read defaults {def_path}: {e}")

    lines = open(new_path, encoding="utf-8").read().splitlines(keepends=True)
    stack, changed = [], []
    seen_new = set()

    for i, line in enumerate(lines):
        raw = line.rstrip("\n")
        if not raw.strip() or raw.lstrip().startswith("#") or raw.lstrip().startswith("- "):
            continue
        m = re.match(r"^(\s*)([^\s:#][^:]*):(.*)$", raw)
        if not m:
            continue
        indent, key, rest = len(m.group(1)), m.group(2).strip(), m.group(3)
        while stack and stack[-1][0] >= indent:
            stack.pop()
        path = ".".join([k for _, k in stack] + [key])
        stack.append((indent, key))
        seen_new.add(path)

        if not rest.strip():            # a mapping header, not a scalar
            continue
        if path in SKIP_PATHS or path.startswith(SKIP_PREFIXES):
            continue
        if path not in old_flat:
            continue
        oldv = old_flat[path]
        if isinstance(oldv, (dict, list)):
            continue
        newv_txt = rest.strip()
        rendered = fmt(oldv, rest)
        if rendered != newv_txt:
            lines[i] = f"{m.group(1)}{m.group(2)}: {rendered}\n"
            changed.append((path, newv_txt, rendered))

    unmapped = [p for p, v in old_flat.items()
                if p not in seen_new and not isinstance(v, (dict, list))
                and p not in SKIP_PATHS and not p.startswith(SKIP_PREFIXES)]
    if changed:
        open(new_path, "w", encoding="utf-8").writelines(lines)
    return ("OK", "", changed, unmapped)


total_changed, report = 0, []
for old_name, new_names in PAIRS:
    op = os.path.join(OLD, old_name)
    if not os.path.isfile(op):
        continue
    remaining = None
    for new_name in new_names:
        np = os.path.join(NEW, new_name)
        r = migrate(op, np, os.path.join(DEF, old_name))
        if r is None:
            print(f"  skip {old_name} -> {new_name} (missing)")
            continue
        status, err, changed, unmapped = r
        if status != "OK":
            print(f"  {old_name}: {status} {err}")
            continue
        total_changed += len(changed)
        print(f"\n### {old_name}  ->  {new_name}   ({len(changed)} values carried over)")
        for p, a, b in changed[:200]:
            print(f"    {p}\n        {a}  ->  {b}")
        remaining = unmapped if remaining is None else [p for p in remaining if p in unmapped]
    if remaining:
        report.append((old_name, remaining))

print(f"\n{'='*70}\nTOTAL values carried over: {total_changed}")
for old_name, unmapped in report:
    print(f"\n--- {old_name}: {len(unmapped)} settings have NO equivalent path in 1.21.4 "
          f"(renamed, moved or removed):")
    for p in sorted(unmapped)[:80]:
        print(f"      {p}")
